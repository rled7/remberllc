import { cp, mkdir, readFile, rm } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const source = new URL('demo-src/dsa/dist/', root);
const target = new URL('public/demos/dsa/', root);
const html = await readFile(new URL('index.html', source), 'utf8');
if (!html.includes('DSA Study Buddy')) throw new Error('Build DSA Study Buddy first.');
await mkdir(new URL('public/demos/', root), { recursive: true });
await rm(target, { recursive: true, force: true });
await cp(source, target, { recursive: true });
console.log('Synced the public DSA Study Buddy demo.');
